"""initial schema

Revision ID: 0001
Revises:
Create Date: 2026-08-24

Hand-authored (not autogenerated — no working Python interpreter was
available in the environment that scaffolded this project to run
`alembic revision --autogenerate` against a live DB).

This intentionally always creates the CURRENT full schema (every table,
every column, on whatever the models look like right now), not a
point-in-time snapshot — that was the original design (see the git
history of this docstring). The tradeoff: every migration from 0002
onward, at the moment it was first written, was adding something not
yet reflected in models.py. Once a later migration's change (a new
column, a new table) gets folded back into the model file it belongs
to, this migration's create_all() picks it up too, and the migration
that originally introduced it becomes redundant, since a genuinely
fresh database now gets that column/table from here instead. That
stopped being harmless once enough columns accumulated: a truly fresh
`alembic upgrade head` started failing with "column already exists" a
few migrations in.

Fixed 2026-08-26 by having this migration also set up the one thing
create_all() can't express, row-level security (previously spread
across migrations 0002/0006/0008/0009/0011/0012/0023 as the policies
were iterated on), and turning every migration from 0002 through 0023
into a documented no-op — see each file's docstring for what it
historically did and why it's now redundant. Revision IDs and the
down_revision chain are unchanged, so a database that already ran the
real version of those migrations (this project's own dev database
included) is unaffected; only a from-scratch install's path changes.
Any future schema change still gets its own new migration, same as
always — this only retires the already-applied history up through
0023, it doesn't change how migrations work going forward.
"""
from alembic import op
